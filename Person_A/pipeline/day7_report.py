#!/usr/bin/env python
"""Day 7: behaviour breakdown + miss analysis + index ground-truth check. Read-only on data."""
import csv, json, re, tarfile, zipfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCAN = ROOT / "data/processed/malicious_scan.jsonl"
INDEX = ROOT / "data/raw/malicious/package_index.jsonl"
PYPI = ROOT / "data/raw/malicious/pypi"
REPORT = ROOT / "Person_A/analysis/real_dataset_behavior_breakdown.md"
GAPS = ROOT / "Person_A/analysis/analyzer_v1_real_data_gaps.md"
TRIAGE = ROOT / "data/processed/zero_finding_triage.csv"
ARCH = (".tar.gz", ".tgz", ".tar.bz2", ".tar.xz", ".tar", ".zip", ".whl")
SEV = {"LOW": 1, "MEDIUM": 2, "HIGH": 3}
KW = ["getattr", "__import__", "importlib", "eval(", "exec(", "compile(", "base64", "marshal", "zlib",
      "pickle", "ctypes", "socket", "subprocess", "os.system", "urllib", "requests", "http.client",
      "webbrowser", "pyperclip", "winreg", "distutils", "os.environ", "open("]
ODD_EXT = {".pth", ".sh", ".bat", ".ps1", ".js", ".exe", ".dll", ".so", ".pyc", ".pyd", ".vbs", ".jar", ".bin", ".dat", ".cmd"}

def norm(n): return re.sub(r"[-_.]+", "-", str(n).strip()).lower()
def pct(a, b): return f"{100 * a / b:.1f}%" if b else "n/a"
def has_setup(r): return any(Path(x.get("file", "")).name.lower() == "setup.py" for x in r.get("results", []))

def inspect(a):
    names, texts = [], []
    try:
        if zipfile.is_zipfile(a):
            with zipfile.ZipFile(a) as z:
                for i in z.infolist():
                    if i.is_dir(): continue
                    names.append(i.filename)
                    if i.filename.lower().endswith(".py") and i.file_size <= 1_000_000:
                        texts.append(z.read(i).decode("utf-8", "replace"))
        else:
            with tarfile.open(a, "r:*") as t:
                for m in t:
                    if not m.isfile(): continue
                    names.append(m.name)
                    if m.name.lower().endswith(".py") and m.size <= 1_000_000:
                        f = t.extractfile(m)
                        if f: texts.append(f.read().decode("utf-8", "replace"))
    except Exception as e:
        names.append(f"!!error:{type(e).__name__}")
    return names, texts

def inspect_dir(r):
    d = PYPI / r["package"] / r["version"]
    names, texts = [], []
    if d.is_dir():
        for a in sorted(d.iterdir()):
            if a.is_file() and a.name.lower().endswith(ARCH):
                n, t = inspect(a); names += n; texts += t
    return names, texts

def fval(o, k):
    x = o.get(k)
    return x.get("value") if isinstance(x, dict) else x

rows = [json.loads(l) for l in open(SCAN, encoding="utf-8") if l.strip()]
n = len(rows)
for r in rows:
    r["_cats"] = set(r["category_counts"])
    r["_ms"] = max((SEV.get(f.get("severity"), 0) for f in r["findings"]), default=0)
names_ct = Counter(norm(r["package_name"]) for r in rows)
u = len(names_ct)
zero = [r for r in rows if not r["findings"]]

L = ["# Real-dataset behaviour breakdown (analyzer v1, static only)", "",
     "Source: Backstabber's Knife Collection, PyPI subset available locally. Generated by `Person_A/pipeline/day7_report.py` from `malicious_scan.jsonl`.",
     "These are **indicator prevalence figures on malicious packages only**. They are not detection rates: no benign scan exists yet.", "",
     "## 1. Denominators", "", "| Item | Count |", "|---|---:|",
     f"| package-versions scanned | {n} |", f"| unique package names | {u} |",
     f"| with >=1 .py file | {sum(r['files_attempted'] > 0 for r in rows)} |",
     f"| failed_static_analysis (>=1 parse error) | {sum(bool(r['failed_static_analysis']) for r in rows)} |",
     f"| zero security findings | {len(zero)} ({pct(len(zero), n)}) |",
     f"| matched to package_index | {sum(bool(r['in_index']) for r in rows)} |",
     f"| index-annotated | {sum(bool(r['index_annotated']) for r in rows)} |",
     f"| not in index | {', '.join(r['package_id'] for r in rows if not r['in_index'])} |", ""]

nm_cats = {}
for r in rows: nm_cats.setdefault(norm(r["package_name"]), set()).update(r["_cats"])
cats = Counter(c for r in rows for c in r["_cats"])
cats_u = Counter(c for s in nm_cats.values() for c in s)
L += ["## 2. Category prevalence", "", f"| Category | package-versions (of {n}) | unique names (of {u}) |", "|---|---:|---:|"]
for c, k in cats.most_common(): L.append(f"| {c} | {k} ({pct(k, n)}) | {cats_u[c]} ({pct(cats_u[c], u)}) |")
sev = Counter(r["_ms"] for r in rows)
L += ["", "Max severity per package-version: " + ", ".join(f"{lab} {sev[v]} ({pct(sev[v], n)})" for v, lab in [(3, "HIGH"), (2, "MEDIUM"), (1, "LOW"), (0, "none")]), ""]

ind = Counter(i for r in rows for i in {f.get("indicator") for f in r["findings"]})
L += ["## 3. Top indicators (package-versions containing them, not raw counts)", "", "| Indicator | package-versions |", "|---|---:|"]
for i, k in ind.most_common(15): L.append(f"| {i} | {k} ({pct(k, n)}) |")
top = names_ct.most_common(10)
L += ["", "## 4. Version concentration (leakage warning for the ML split)", "",
      f"Top names by number of versions: {', '.join(f'{a} ({b})' for a, b in top)}. These 10 names make up {pct(sum(b for _, b in top), n)} of all rows.",
      "Versions of one package are near-duplicates, so B must split by `package_name`, not by row.",
      "Largest finding counts come from packages that bundle large legitimate libraries: " +
      ", ".join(f"{r['package_id']} ({r['findings_count']})" for r in sorted(rows, key=lambda r: -r['findings_count'])[:5]) +
      ". Raw finding counts are therefore not meaningful; use presence per package.", ""]

with_setup = [r for r in rows if has_setup(r)]
no_setup = [r for r in rows if not has_setup(r)]
it_with = sum("Install-Time / Package Execution" in r["_cats"] for r in with_setup)
it_no = sum("Install-Time / Package Execution" in r["_cats"] for r in no_setup)
print(f"inspecting {len(no_setup)} rows without setup.py ...")
pyproject = other_no = nopy = 0
oddext_all = Counter()
for k, r in enumerate(no_setup):
    names, _ = inspect_dir(r)
    base = [Path(x).name.lower() for x in names]
    if "pyproject.toml" in base: pyproject += 1
    elif r["files_attempted"] == 0: nopy += 1
    else: other_no += 1
    for x in names:
        e = Path(x).suffix.lower()
        if e in ODD_EXT: oddext_all[e] += 1
L += ["## 5. Install-time path (setup.py)", "", "| Group | package-versions | with Install-Time finding |", "|---|---:|---:|",
      f"| setup.py scanned | {len(with_setup)} ({pct(len(with_setup), n)}) | {it_with} ({pct(it_with, len(with_setup))}) |",
      f"| no setup.py scanned | {len(no_setup)} ({pct(len(no_setup), n)}) | {it_no} ({pct(it_no, len(no_setup))}) |", "",
      f"Of the {len(no_setup)} without setup.py: {pyproject} ship a pyproject.toml (build-backend based install), {nopy} contain no .py at all, {other_no} are other layouts.",
      "Install-time behaviour in pyproject-based packages (build backends, .pth files, setup.cfg hooks) is outside analyzer v1.",
      "Odd non-.py files in those archives: " + (", ".join(f"{e} x{c}" for e, c in oddext_all.most_common()) or "none"), ""]

print(f"triaging {len(zero)} zero-finding rows ...")
tri, reasons = [], Counter()
kwtot = Counter()
for r in zero:
    names, texts = inspect_dir(r)
    blob = "\n".join(texts)
    hits = [k for k in KW if k in blob]
    odd = sorted({Path(x).suffix.lower() for x in names if Path(x).suffix.lower() in ODD_EXT})
    if r["files_attempted"] == 0: why = "no_python_source"
    elif r["failed_static_analysis"]: why = "parse_failed"
    elif [h for h in hits if h not in ("open(", "os.environ")]: why = "risky_keywords_unflagged"
    else: why = "no_risky_keywords"
    reasons[why] += 1; kwtot.update(hits)
    tri.append([r["package_id"], r["files_attempted"], why, " ".join(hits), " ".join(odd), len(blob)])
with open(TRIAGE, "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f); w.writerow(["package_id", "n_py", "reason", "keywords", "odd_ext", "py_chars"]); w.writerows(tri)
L += ["## 6. Zero-finding packages (miss analysis)", "", f"{len(zero)} of {n} package-versions ({pct(len(zero), n)}) produced no security finding.", "",
      "| Reason | count |", "|---|---:|"] + [f"| {a} | {b} |" for a, b in reasons.most_common()] + [
      "", "Keywords present in the source of zero-finding packages (candidate analyzer gaps): " + ", ".join(f"{k} ({v})" for k, v in kwtot.most_common(12)),
      "", "First 30 for manual reading (full list: `data/processed/zero_finding_triage.csv`):", "", "| package | .py | reason | keywords |", "|---|---:|---|---|"]
L += [f"| {t[0]} | {t[1]} | {t[2]} | {t[3]} |" for t in tri[:30]] + [""]

idx = {}
for line in open(INDEX, encoding="utf-8"):
    o = json.loads(line); purl = (o.get("purl") or {}).get("value") or ""
    if purl.startswith("pkg:pypi/"):
        nm, _, ver = purl[9:].rpartition("@"); idx[(norm(nm), ver)] = o
ann = [(r, idx.get((norm(r["package_name"]), r["version"]))) for r in rows if r["index_annotated"]]
ann = [(r, o) for r, o in ann if o]
trig = Counter(str(fval(o, "trigger")) for _, o in ann); obf = Counter(str(fval(o, "obfuscated")) for _, o in ann)
t_rows = [r for r, o in ann if "install" in str(fval(o, "trigger")).lower()]
o_rows = [r for r, o in ann if str(fval(o, "obfuscated")).lower() in ("true", "yes", "1", "obfuscated")]
t_hit = sum("Install-Time / Package Execution" in r["_cats"] for r in t_rows)
o_hit = sum("Obfuscation" in r["_cats"] for r in o_rows)
any_hit = sum(bool(r["findings"]) for r, _ in ann)
L += ["## 7. Agreement with the dataset's own annotations", "", f"Annotated package-versions compared: {len(ann)}.", "",
      "| Annotation says | n | analyzer agrees | rate |", "|---|---:|---:|---:|",
      f"| any malicious package (>=1 finding) | {len(ann)} | {any_hit} | {pct(any_hit, len(ann))} |",
      f"| trigger mentions install | {len(t_rows)} | {t_hit} (Install-Time) | {pct(t_hit, len(t_rows))} |",
      f"| obfuscated = true | {len(o_rows)} | {o_hit} (Obfuscation) | {pct(o_hit, len(o_rows))} |", "",
      "trigger values: " + str(trig.most_common(8)), "", "obfuscated values: " + str(obf.most_common(5)), ""]
REPORT.parent.mkdir(parents=True, exist_ok=True)
if REPORT.exists(): REPORT.rename(str(REPORT) + ".bak")
REPORT.write_text("\n".join(L), encoding="utf-8")

G = ["# Analyzer v1: gaps observed on real data", "",
     "Analyzer v1 is frozen as the baseline. Changes go into a documented v1.1 only. Evidence: `real_dataset_behavior_breakdown.md`.", "",
     "| # | Gap | Evidence |", "|---|---|---|",
     f"| 1 | getattr-style indirection is not resolved | Evasion test: 2 of 13 variants succeeded (ASR 15.38%); {kwtot['getattr']} zero-finding packages contain `getattr` |",
     f"| 2 | Install-time behaviour outside setup.py | {len(no_setup)} package-versions have no setup.py; {pyproject} use pyproject.toml; Install-Time rate {pct(it_no, len(no_setup))} vs {pct(it_with, len(with_setup))} when setup.py exists |",
     f"| 3 | Packages without Python source | {reasons['no_python_source']} zero-finding package-versions contain no .py; odd files: {', '.join(oddext_all) or 'none'} |",
     f"| 4 | Python that fails to parse | {sum(bool(r['failed_static_analysis']) for r in rows)} package-versions (partial analysis); reported as failed_static_analysis, not as a security category |",
     f"| 5 | Risky keywords present but unflagged | {reasons['risky_keywords_unflagged']} zero-finding package-versions; see triage CSV |",
     f"| 6 | `distutils` setup not recognised (to verify) | `distutils` appears in {kwtot['distutils']} zero-finding packages |",
     "| 7 | Supply-chain abuse (typosquatting) | Metadata/name based, cannot be found by AST analysis by design; owned by Person B's name-similarity feature |", "",
     "Limits: static analysis only; indicators are not proof of malice; no benign baseline yet, so discrimination is unmeasured.", ""]
if GAPS.exists(): GAPS.rename(str(GAPS) + ".bak")
GAPS.write_text("\n".join(G), encoding="utf-8")

print("\n".join(L[:70]))
print("\nwrote", REPORT, GAPS, TRIAGE)
